using System.Text;
using Microsoft.Extensions.Logging;
using NexusMods.Abstractions.Loadouts.Synchronizers;
using NexusMods.Games.CreationEngine.Abstractions;
using NexusMods.MnemonicDB.Abstractions;
using NexusMods.Sdk.FileStore;
using NexusMods.Sdk.Games;
using NexusMods.Sdk.Loadouts;

namespace NexusMods.Games.CreationEngine;

public class PluginsFile(ILogger<PluginsFile> logger, ICreationEngineGame game) : IIntrinsicFile
{
    public GamePath Path { get; } = game.PluginsFile;

    public async Task Validate(Loadout.ReadOnly loadout, IReadOnlyDictionary<GamePath, SyncNode> syncTree, CancellationToken cancellationToken)
    {
        var order = await PluginLoadOrder.Read(game, syncTree, loadout.InstallationInstance.Locations, cancellationToken);
        order.ThrowIfInvalid();
    }

    public async Task Write(Stream stream, Loadout.ReadOnly loadout, Dictionary<GamePath, SyncNode> syncTree)
    {
        var order = await PluginLoadOrder.Read(game, syncTree, loadout.InstallationInstance.Locations);
        order.ThrowIfInvalid();
        logger.LogDebug("Sorted {Count} plugin files", order.SortedPlugins.Count);

        // The game supplies the activation/order of its installed base-game and DLC plugins.
        var official = game.OfficialPlugins.ToHashSet();
        await using var writer = new StreamWriter(stream, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false), leaveOpen: true)
        {
            NewLine = "\r\n",
        };
        await writer.WriteLineAsync("# Generated by Nexus Mods App Rework");
        foreach (var plugin in order.SortedPlugins)
        {
            if (official.Contains(plugin.Key)) continue;
            await writer.WriteLineAsync($"*{plugin.Path.FileName}");
        }
        await writer.FlushAsync();
    }

    public Task Ingest(Stream stream, Loadout.ReadOnly loadout, Dictionary<GamePath, SyncNode> syncTree, ITransaction tx)
    {
        // Independent plugin activation and imported ordering need a persistent loadout model.
        // Until then, activation follows enabled files and ordering follows header dependencies.
        return Task.CompletedTask;
    }
}
